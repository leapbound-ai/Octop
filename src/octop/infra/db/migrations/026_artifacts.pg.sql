CREATE TABLE IF NOT EXISTS artifacts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  artifact_id TEXT NOT NULL UNIQUE,
  agent_id TEXT NOT NULL REFERENCES agents(agent_id) ON DELETE CASCADE,
  thread_id TEXT NOT NULL REFERENCES threads(thread_id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  path TEXT NOT NULL,
  title TEXT NOT NULL,
  mime_kind TEXT NOT NULL,
  kind TEXT NOT NULL DEFAULT 'file',
  summary TEXT NOT NULL DEFAULT '',
  payload TEXT NOT NULL DEFAULT '{}',
  schema_version INTEGER NOT NULL DEFAULT 1,
  tags TEXT NOT NULL DEFAULT '[]',
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'archived', 'ignored')),
  parent_id TEXT NOT NULL DEFAULT '',
  refs TEXT NOT NULL DEFAULT '[]',
  source TEXT NOT NULL DEFAULT 'tool',
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  UNIQUE (agent_id, thread_id, path)
);
CREATE INDEX IF NOT EXISTS idx_artifacts_user_status ON artifacts(user_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_artifacts_thread ON artifacts(thread_id);
CREATE INDEX IF NOT EXISTS idx_artifacts_agent ON artifacts(agent_id);

UPDATE _schema_version SET version = 26;
